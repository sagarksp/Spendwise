import type { Category, Expense, FixedExpense, SpendingLimit } from './types';
import { monthlyBudgetExpenses } from './domain';

interface MonthlyPdfInput {
  cycleLabel: string;
  start: string;
  end: string;
  expenses: Expense[];
  categories: Category[];
  fixedExpenses: FixedExpense[];
  monthlyBudget?: SpendingLimit;
  categoryLimits: SpendingLimit[];
  dailyTotals: Array<{ date: string; amountPaise: number }>;
}

type Line = { text: string; size?: number; color?: string; bold?: boolean; gap?: number };

const ascii = (value: string) => value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[₹]/g, 'INR ').replace(/[^\x20-\x7e]/g, '?');
const escapePdf = (value: string) => ascii(value).replaceAll('\\', '\\\\').replaceAll('(', '\\(').replaceAll(')', '\\)');
const amount = (paise: number) => `INR ${(paise / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

function wrap(value: string, max = 86): string[] {
  const words = ascii(value).split(/\s+/);
  const lines: string[] = [];
  let line = '';
  for (const word of words) {
    if (!word) continue;
    if (line && `${line} ${word}`.length > max) { lines.push(line); line = word; }
    else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines.length ? lines : [''];
}

function streamForPage(lines: Line[], pageNumber: number, pageCount: number, firstPage: boolean, highlights: string[]): string {
  const commands = [
    '0.18 0.20 0.53 rg 0 750 595 92 re f',
    'BT /F2 23 Tf 0.99 0.99 1 rg 44 803 Td (Spendwise) Tj ET',
    'BT /F1 11 Tf 0.87 0.89 1 rg 44 779 Td (Monthly expense report) Tj ET',
    `BT /F1 9 Tf 0.87 0.89 1 rg 430 785 Td (${pageNumber} / ${pageCount}) Tj ET`,
    '0.38 0.39 0.82 rg 44 738 48 4 re f'
  ];
  if (firstPage) {
    commands.push('0.95 0.95 1 rg 44 670 158 48 re f', '0.97 0.96 0.91 rg 218 670 158 48 re f', '0.92 0.97 0.95 rg 392 670 158 48 re f');
    highlights.forEach((value, index) => {
      const x = [54, 228, 402][index];
      commands.push(`BT /F1 8 Tf 0.43 0.45 0.55 rg ${x} 703 Td (${escapePdf(['TOTAL EXPENSES', 'BUDGET PLAN', 'ENTRIES'][index])}) Tj ET`);
      commands.push(`BT /F2 11 Tf 0.18 0.20 0.53 rg ${x} 683 Td (${escapePdf(value)}) Tj ET`);
    });
  }
  let y = firstPage ? 644 : 720;
  for (const line of lines) {
    const size = line.size ?? 10;
    const color = line.color ?? '0.16 0.18 0.31';
    const boldFont = line.bold ? 'F2' : 'F1';
    const wrapped = wrap(line.text, size >= 15 ? 65 : 88);
    for (const text of wrapped) {
      if (y < 52) break;
      commands.push(`BT /${boldFont} ${size} Tf ${color} rg 48 ${y} Td (${escapePdf(text)}) Tj ET`);
      y -= size >= 15 ? 23 : size >= 12 ? 19 : 15;
    }
    y -= line.gap ?? 0;
  }
  commands.push(`BT /F1 8 Tf 0.46 0.48 0.57 rg 44 29 Td (Generated by Spendwise) Tj ET`);
  return commands.join('\n');
}

export function monthlyReportPdf(input: MonthlyPdfInput): Blob {
  const normalExpenses = input.expenses.filter((expense) => !expense.fixedExpenseId);
  const fixedExpensesInReport = input.expenses.filter((expense) => Boolean(expense.fixedExpenseId));
  const total = input.expenses.reduce((sum, expense) => sum + expense.amountPaise, 0);
  const includedFixedTotal = monthlyBudgetExpenses(fixedExpensesInReport, input.fixedExpenses).reduce((sum, expense) => sum + expense.amountPaise, 0);
  const budgetCounted = monthlyBudgetExpenses(input.expenses, input.fixedExpenses).reduce((sum, expense) => sum + expense.amountPaise, 0);
  const categories = input.categories.map((category) => ({
    category,
    amount: normalExpenses.filter((expense) => expense.categoryId === category.id).reduce((sum, expense) => sum + expense.amountPaise, 0),
    limit: input.categoryLimits.find((limit) => limit.categoryId === category.id && !limit.deleted)
  })).filter((row) => row.amount > 0 || row.limit).sort((a, b) => b.amount - a.amount);

  const lines: Line[] = [
    { text: input.cycleLabel, size: 15, color: '0.18 0.20 0.53', bold: true, gap: 3 },
    { text: `Cycle: ${input.start} to ${input.end}`, color: '0.42 0.44 0.54' },
    { text: `Total expenses: ${amount(total)}`, size: 12, bold: true },
    { text: `Counted toward monthly budget: ${amount(budgetCounted)}${input.monthlyBudget ? ` of ${amount(input.monthlyBudget.amountPaise)}` : ' (budget not set)'}`, color: '0.30 0.32 0.44', gap: 8 },
    { text: 'CATEGORY SUMMARY', size: 11, color: '0.18 0.20 0.53', bold: true, gap: 2 },
    ...categories.map(({ category, amount: spent, limit }) => ({ text: `${category.name}: ${amount(spent)}${limit ? ` / ${amount(limit.amountPaise)}` : ''}`, gap: 1 })),
    { text: `Fixed expenses: ${amount(fixedExpensesInReport.reduce((sum, expense) => sum + expense.amountPaise, 0))} (${fixedExpensesInReport.length} entries; ${amount(includedFixedTotal)} counted toward budget)`, color: '0.30 0.32 0.44', gap: 8 },
    { text: 'DAILY TOTALS', size: 11, color: '0.18 0.20 0.53', bold: true, gap: 2 },
    ...input.dailyTotals.map((day) => ({ text: `${day.date}    ${amount(day.amountPaise)}` })),
    { text: 'EXPENSE DETAILS', size: 11, color: '0.18 0.20 0.53', bold: true, gap: 2 },
    ...input.expenses.slice().sort((a, b) => a.spentOn.localeCompare(b.spentOn)).map((expense) => {
      const categoryName = expense.fixedExpenseId ? 'Fixed expense' : input.categories.find((category) => category.id === expense.categoryId)?.name ?? 'Other';
      return { text: `${expense.spentOn} | ${expense.itemName} | ${categoryName} | ${amount(expense.amountPaise)}` };
    })
  ];

  const pages: Line[][] = [];
  let current: Line[] = [];
  let estimatedLines = 0;
  for (const line of lines) {
    const count = wrap(line.text, line.size && line.size >= 15 ? 65 : 88).length;
    const capacity = pages.length === 0 ? 36 : 43;
    if (estimatedLines + count > capacity) {
      pages.push(current);
      current = [];
      estimatedLines = 0;
    }
    current.push(line);
    estimatedLines += count + (line.gap ? 1 : 0);
  }
  pages.push(current);

  const objects: string[] = [];
  const pageObjectIds = pages.map((_, index) => 3 + index * 2);
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[2] = `<< /Type /Pages /Kids [${pageObjectIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pages.length} >>`;
  pages.forEach((page, index) => {
    const pageId = pageObjectIds[index];
    const contentId = pageId + 1;
    const stream = streamForPage(page, index + 1, pages.length, index === 0, [amount(total), input.monthlyBudget ? amount(input.monthlyBudget.amountPaise) : 'Not set', String(input.expenses.length)]);
    objects[pageId] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${3 + pages.length * 2} 0 R /F2 ${4 + pages.length * 2} 0 R >> >> /Contents ${contentId} 0 R >>`;
    objects[contentId] = `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`;
  });
  const fontId = 3 + pages.length * 2;
  objects[fontId] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>';
  objects[fontId + 1] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>';

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  for (let id = 1; id < objects.length; id += 1) {
    offsets[id] = pdf.length;
    pdf += `${id} 0 obj\n${objects[id]}\nendobj\n`;
  }
  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let id = 1; id < objects.length; id += 1) pdf += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return new Blob([pdf], { type: 'application/pdf' });
}
